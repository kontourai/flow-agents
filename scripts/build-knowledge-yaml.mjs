import { build } from "esbuild";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(import.meta.url);
const packagePath = require.resolve("yaml/package.json");
const { version } = JSON.parse(readFileSync(packagePath, "utf8"));
const expected = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).devDependencies.yaml;
if (version !== expected) throw new Error("Knowledge YAML generator requires the pinned yaml package.");
if (process.argv.slice(2).some((arg) => arg !== "--check")) throw new Error("Usage: build-knowledge-yaml.mjs [--check]");
const check = process.argv.includes("--check");
const output = join(root, "kits/knowledge/adapters/shared/vendor");
// The package's default ESM export bundles without the Node CJS entry's dynamic require calls.
const result = await build({
  stdin: { contents: 'export { parseDocument, stringify, isMap, isSeq } from "yaml";', resolveDir: root, sourcefile: "knowledge-yaml-entry.js" },
  bundle: true, platform: "neutral", format: "esm", target: "node22", minify: true,
  write: false, metafile: true, legalComments: "inline",
  banner: { js: `// Generated by npm run knowledge:yaml:generate from yaml ${version}; do not edit.\n// ISC license: ./yaml.LICENSE` },
});
if (Object.values(result.metafile.outputs).some((value) => value.imports.length)) throw new Error("Knowledge YAML bundle must be self-contained.");
const files = new Map([
  ["yaml.mjs", result.outputFiles[0].text],
  ["yaml.LICENSE", readFileSync(join(dirname(packagePath), "LICENSE"), "utf8")],
]);
if (!check) mkdirSync(output, { recursive: true });
for (const [name, content] of files) {
  const path = join(output, name);
  if (check) {
    if (readFileSync(path, "utf8") !== content) throw new Error(`Stale generated Knowledge YAML artifact: ${name}`);
  } else writeFileSync(path, content);
}
console.error(`Knowledge YAML artifacts ${check ? "verified" : "generated"} (yaml ${version}).`);
